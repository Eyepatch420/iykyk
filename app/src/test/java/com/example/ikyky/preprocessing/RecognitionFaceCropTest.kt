/**
 * Phase 6E — the 5-point recognition crop.
 *
 * This is the single highest-risk component of the port: a swapped eye mapping
 * produces a horizontally mirrored transform that silently degrades every
 * embedding with no error anywhere. Several tests here exist specifically to
 * fail if that swap is ever reintroduced.
 *
 * The numeric expectations are GOLDEN VALUES generated by the frozen Python
 * reference (`ikyky_lab/preprocessing/align.py::_umeyama`) on the same inputs.
 */
class RecognitionFaceCropTest {

    private val tpl = RecognitionFaceCrop.ARCFACE_TEMPLATE_112

    // -- helpers -------------------------------------------------------------

    /**
     * Builds a face whose landmarks are placed by VIEWER position.
     *
     * Labels follow the convention MEASURED on device (235/235 detections):
     * ML Kit's `LEFT_EYE` lands at the smaller x. Because slots are resolved by
     * position rather than by label, the labelling here only affects which name
     * carries which point — never the resulting geometry (see
     * `theOppositeLabelConventionProducesTheSameGeometry`).
     */
    private fun face(
        viewerLeftEye: Pair<Float, Float>,
        viewerRightEye: Pair<Float, Float>,
        nose: Pair<Float, Float>,
        viewerLeftMouth: Pair<Float, Float>,
        viewerRightMouth: Pair<Float, Float>,
        box: BoundingBox = BoundingBox(380, 270, 530, 440),
    ) = DetectedFace(
        boundingBox = box,
        landmarks = listOf(
            Landmark(LandmarkType.LEFT_EYE, viewerLeftEye.first, viewerLeftEye.second),
            Landmark(LandmarkType.RIGHT_EYE, viewerRightEye.first, viewerRightEye.second),
            Landmark(LandmarkType.NOSE_BASE, nose.first, nose.second),
            Landmark(LandmarkType.MOUTH_LEFT, viewerLeftMouth.first, viewerLeftMouth.second),
            Landmark(LandmarkType.MOUTH_RIGHT, viewerRightMouth.first, viewerRightMouth.second),
        ),
    )

    /** The same physical face labelled the OTHER way (subject-relative). */
    private fun subjectRelativeFace() = DetectedFace(
        boundingBox = BoundingBox(380, 270, 530, 440),
        landmarks = listOf(
            Landmark(LandmarkType.RIGHT_EYE, 412.3f, 301.7f),
            Landmark(LandmarkType.LEFT_EYE, 498.1f, 296.4f),
            Landmark(LandmarkType.NOSE_BASE, 452.0f, 352.9f),
            Landmark(LandmarkType.MOUTH_RIGHT, 419.8f, 404.2f),
            Landmark(LandmarkType.MOUTH_LEFT, 489.5f, 399.1f),
        ),
    )

    private fun realisticFace() = face(
        viewerLeftEye = 412.3f to 301.7f,
        viewerRightEye = 498.1f to 296.4f,
        nose = 452.0f to 352.9f,
        viewerLeftMouth = 419.8f to 404.2f,
        viewerRightMouth = 489.5f to 399.1f,
    )

    private fun arr(vararg p: Pair<Double, Double>) =
        Array(p.size) { doubleArrayOf(p[it].first, p[it].second) }

