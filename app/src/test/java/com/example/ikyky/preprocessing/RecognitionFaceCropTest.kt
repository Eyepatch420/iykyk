    // OUTPUT SIZE
    // =======================================================================

    @Test
    fun transformMapsLandmarksOntoTheScaledTemplate_at224() {
        val f = realisticFace()
        val m = RecognitionFaceCrop.transformFor(f, 224)!!
        val src = RecognitionFaceCrop.orderedLandmarks(f)!!
        val t224 = RecognitionFaceCrop.templateFor(224)
        // scale doubles relative to the 112 fit
        val m112 = RecognitionFaceCrop.transformFor(f, 112)!!
        assertEquals(m112.a * 2.0, m.a, 1e-6)
        // and the residuals also double
        for (i in 0 until 5) {
            val p = m.apply(src[i][0], src[i][1])
            assertTrue(hypot(p[0] - t224[i][0], p[1] - t224[i][1]) < 3.0)
        }
    }

    @Test
    fun nonPositiveOutputSizeIsRejected() {
        assertNull(RecognitionFaceCrop.transformFor(realisticFace(), 0))
        assertNull(RecognitionFaceCrop.transformFor(realisticFace(), -112))
    }
