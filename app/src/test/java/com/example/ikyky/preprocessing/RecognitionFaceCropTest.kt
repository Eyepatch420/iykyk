    @Test
    fun transformIsNeverAReflection_determinantStaysPositive() {
        val m = RecognitionFaceCrop.transformFor(realisticFace(), 112)!!
        assertTrue("a similarity transform must not mirror", m.determinant > 0.0)
    }

    @Test
    fun umeyama_onMirroredInput_stillReturnsAProperRotation() {
        // Feed a horizontally mirrored point set. Umeyama's sign fix forbids a
        // reflection, so the best proper-rotation fit comes back with a POSITIVE
        // determinant — it cannot express the mirror, which is exactly the
        // guarantee we want.
        val src = Array(5) { doubleArrayOf(200.0 - tpl[it][0], tpl[it][1]) }
        val m = RecognitionFaceCrop.umeyama(src, tpl)!!
        assertTrue("must never produce a reflection", m.determinant > 0.0)
    }

    @Test
    fun umeyama_scaleIsUniform_onBothAxes() {
        val m = RecognitionFaceCrop.umeyama(
            arr(412.3 to 301.7, 498.1 to 296.4, 452.0 to 352.9, 419.8 to 404.2, 489.5 to 399.1),
            tpl,
        )!!
        // for a similarity transform [[a,b],[c,d]] = s*R, so a == d and b == -c
        assertEquals("a and d must match (uniform scale)", m.a, m.d, 1e-9)
        assertEquals("b must be -c (pure rotation)", m.b, -m.c, 1e-9)
    }

    @Test
    fun umeyama_returnsNullOnDegenerateInput() {
        val coincident = arr(1.0 to 1.0, 1.0 to 1.0, 1.0 to 1.0, 1.0 to 1.0, 1.0 to 1.0)
        val m = RecognitionFaceCrop.umeyama(coincident, tpl)
        // scale falls back to 1.0 on zero variance; either a null or a
        // finite-but-degenerate matrix is acceptable, but it must not be NaN.
        if (m != null) {
            assertTrue(m.a.isFinite() && m.d.isFinite() && m.tx.isFinite() && m.ty.isFinite())
        }
    }

